/**
 * ============================================================================
 * TALKASTROLOGER - FRONTEND DEPLOYMENT BUNDLER
 * ============================================================================
 * Runs automatically after `next build` to assemble the clean `out/`
 * deployment folder and `out.zip` archive containing only the frontend
 * production files ready for Hostinger / VPS / cPanel deployment.
 * ============================================================================
 */

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const ROOT_DIR = path.resolve(__dirname, "..");
const OUT_DIR = path.join(ROOT_DIR, "out");
const ZIP_PATH = path.join(ROOT_DIR, "out.zip");

console.log("\n📦 [Deploy Bundler] Assembling frontend deployment output...");

// 1. Clean or create out directory
if (fs.existsSync(OUT_DIR)) {
  fs.rmSync(OUT_DIR, { recursive: true, force: true });
}
fs.mkdirSync(OUT_DIR, { recursive: true });

// Helper: Copy directory recursively
function copyDirRecursive(src, dest, ignoreNames = []) {
  if (!fs.existsSync(src)) return;
  fs.mkdirSync(dest, { recursive: true });
  const entries = fs.readdirSync(src, { withFileTypes: true });

  for (const entry of entries) {
    if (ignoreNames.includes(entry.name)) continue;
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);

    if (entry.isDirectory()) {
      copyDirRecursive(srcPath, destPath, ignoreNames);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

// 2. Copy .next directory (excluding heavy cache)
console.log("  → Copying .next build artifacts...");
copyDirRecursive(
  path.join(ROOT_DIR, ".next"),
  path.join(OUT_DIR, ".next"),
  ["cache", "dev"]
);

// 3. Copy public directory
console.log("  → Copying public assets...");
copyDirRecursive(path.join(ROOT_DIR, "public"), path.join(OUT_DIR, "public"));

// 4. Copy .htaccess if present
const htaccessPath = path.join(ROOT_DIR, ".htaccess");
if (fs.existsSync(htaccessPath)) {
  console.log("  → Copying .htaccess (LiteSpeed / Apache config)...");
  fs.copyFileSync(htaccessPath, path.join(OUT_DIR, ".htaccess"));
}

// 5. Copy next.config.ts if present
const nextConfigPath = path.join(ROOT_DIR, "next.config.ts");
if (fs.existsSync(nextConfigPath)) {
  fs.copyFileSync(nextConfigPath, path.join(OUT_DIR, "next.config.ts"));
}

// 6. Generate production package.json for frontend
console.log("  → Generating production package.json for frontend...");
const rootPackageJson = JSON.parse(
  fs.readFileSync(path.join(ROOT_DIR, "package.json"), "utf-8")
);

const deployPackageJson = {
  name: "talkastrologer-frontend",
  version: rootPackageJson.version || "1.0.0",
  private: true,
  scripts: {
    start: "next start -p 3000",
    "start:custom": "node server.js",
  },
  dependencies: { ...rootPackageJson.dependencies },
};
// Clean up any backend-only dependencies from frontend bundle
delete deployPackageJson.dependencies["cors"];

fs.writeFileSync(
  path.join(OUT_DIR, "package.json"),
  JSON.stringify(deployPackageJson, null, 2)
);

// 7. Generate server.js runner for Hostinger Node.js / Passenger / cPanel
console.log("  → Generating Hostinger / Passenger server.js runner...");
const standaloneServerJs = `const { createServer } = require("http");
const next = require("next");

const port = parseInt(process.env.PORT, 10) || 3000;
const dev = false;
const app = next({ dev });
const handle = app.getRequestHandler();

app.prepare().then(() => {
  createServer((req, res) => {
    handle(req, res);
  }).listen(port, "0.0.0.0", (err) => {
    if (err) throw err;
    console.log(\`> Next.js Frontend ready on http://0.0.0.0:\${port}\`);
  });
});
`;
fs.writeFileSync(path.join(OUT_DIR, "server.js"), standaloneServerJs);

// 8. Generate ecosystem.config.js for PM2 deployments
console.log("  → Generating PM2 ecosystem.config.js...");
const ecosystemConfig = `module.exports = {
  apps: [
    {
      name: "astro-frontend",
      script: "server.js",
      instances: "max",
      exec_mode: "cluster",
      env: {
        NODE_ENV: "production",
        PORT: 3000,
      },
    },
  ],
};
`;
fs.writeFileSync(path.join(OUT_DIR, "ecosystem.config.js"), ecosystemConfig);

// 9. Generate deployment instructions README
const deployReadme = `# TalkAstrologer Frontend Deployment

This folder was automatically generated by \`npm run build\`.
It contains ONLY the production frontend application.

## Quick Hostinger Deployment (Option A - File Manager):
1. Zip this \`out/\` folder (or use \`out.zip\` generated alongside).
2. Upload and extract to your website directory (e.g. \`public_html\`).
3. Run \`npm install --production\` in that folder.
4. Start via Hostinger Node.js manager (Startup file: \`server.js\`).

## VPS / PM2 Deployment (Option B):
\`\`\`bash
cd /path/to/deployed/frontend
npm install --omit=dev
pm2 start ecosystem.config.js
pm2 save
\`\`\`
`;
fs.writeFileSync(path.join(OUT_DIR, "DEPLOY.md"), deployReadme);

// 10. Generate out.zip for convenient 1-click upload
console.log("  → Creating out.zip archive for 1-click upload...");
try {
  if (fs.existsSync(ZIP_PATH)) {
    fs.unlinkSync(ZIP_PATH);
  }
  execSync(`cd "${OUT_DIR}" && zip -r -q "${ZIP_PATH}" . *`, {
    stdio: "ignore",
  });
  const zipStats = fs.statSync(ZIP_PATH);
  const sizeMb = (zipStats.size / (1024 * 1024)).toFixed(2);
  console.log(`  ✓ Created out.zip (${sizeMb} MB) successfully.`);
} catch (zipErr) {
  console.warn("  ℹ Could not auto-generate zip (system zip utility not available):", zipErr.message);
}

console.log("\n✅ [Deploy Bundler] Frontend deployment output updated successfully!");
console.log(`📁 Deployment Folder:  ${OUT_DIR}`);
console.log(`📦 Deployment Archive: ${ZIP_PATH}\n`);
